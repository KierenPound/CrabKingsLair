-- Support tickets submitted from the UnderCroft support form.
-- Inserts arrive from the Cloudflare Worker at worker.crabkingslair.com/api/support.
-- Reads are done server-side with the service role key, so no anon SELECT policy exists here.

drop trigger if exists "send-ticket-email-hook" on public.support_tickets;
drop table if exists public.support_tickets;

create table public.support_tickets (
  id            bigint generated by default as identity primary key,
  created_at    timestamptz not null default timezone('utc'::text, now()),

  -- Submitter
  user_email    text,
  user_name     text,
  user_id       uuid default gen_random_uuid(),

  -- Ticket details
  subject       text,
  message       text,
  screenshot    text,                 -- base64 data URL, embedded inline in the notification email
  platform      text default 'ios'::text,
  app_version   text,

  -- Internal management
  status        text not null default 'open'::text,
  notes         text
);

alter table public.support_tickets enable row level security;

create policy "Anyone can submit a support ticket"
  on public.support_tickets for insert to anon, authenticated with check (true);

-- Fires the Supabase edge function that emails the ticket on to Brevo.
create trigger "send-ticket-email-hook"
  after insert on public.support_tickets for each row
  execute function supabase_functions.http_request(
    'https://khvydomhfyqhepkvcdsh.supabase.co/functions/v1/send-ticket-email',
    'POST',
    '{"Content-type":"application/json"}',
    '{}',
    '5000'
  );
